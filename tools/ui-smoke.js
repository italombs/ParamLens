#!/usr/bin/env node
// UI smoke test in a real Chromium (Playwright).
//   node tools/ui-smoke.js build/ParamLens.html build/parity/export.tsv [linux-binary]
// 1) ParamLens.html over file:// (file mode), language switch, 2) exported report,
// 3) the server (.exe) with demo data and the switch to file mode. Screenshots in build/shots/.
"use strict";
const path = require("path");
const fs = require("fs");
const { spawn } = require("child_process");
const { chromium } = require("playwright");

const [htmlPath, tsvPath, binPath] = process.argv.slice(2);
const shots = path.resolve("build/shots");
fs.mkdirSync(shots, { recursive: true });
let failures = 0;
const check = (cond, msg) => { console.log((cond ? "ok     " : "FAILED ") + msg); if (!cond) failures++; };

async function analyzeFile(page, tsv) {
  await page.setInputFiles("#fFile", tsv);
  await page.click("#btnFileAnalyze");
  await page.waitForSelector("#vRes:not(.hidden)", { timeout: 60000 });
}

async function checkResults(page, label, { samples }) {
  const fams = await page.$$eval("#famList .fam", els => els.length);
  check(fams === 16, `${label}: 16 queries in the list (${fams})`);
  const kpi = await page.textContent("#totKpis");
  check(/Executions/.test(kpi) && /Findings/.test(kpi), `${label}: KPIs in English`);
  const nFind = await page.$$eval("#tFindings .find", els => els.length);
  check(nFind >= 30, `${label}: findings listed (${nFind})`);
  const f0 = await page.textContent("#tFindings .find .tt");
  check(/^Catch-all: @qploDropdownAssigneeId = 0 is true in 90\.\d% of executions$/.test(f0), `${label}: finding text built by the UI (${f0})`);
  await page.click("#famList .fam");
  await page.waitForSelector("#tFamily:not(.hidden) #ptab");
  const params = await page.$$eval("#ptab tr.click", els => els.length);
  check(params > 5, `${label}: parameter table (${params})`);
  await page.click("#ptab tr.click");
  check(await page.isVisible("#pd0:not(.hidden) table"), `${label}: value distribution opens`);
  const fam = await page.textContent("#tFamily");
  check(/Call shapes/.test(fam) && /pass-through/.test(fam) && /filter/.test(fam), `${label}: call shapes`);
  if (samples) {
    const before = await page.textContent("#comboTab");
    await page.click("#chips .chip:not(.on)");
    await page.waitForFunction(b => document.querySelector("#comboTab").textContent !== b && !/computing/.test(document.querySelector("#comboTab").textContent), before);
    check(/combination/.test(await page.textContent("#comboTab")), `${label}: combination recomputed`);
    await page.click("#tFamily [data-sample]");
    await page.waitForFunction(() => /DECLARE|exec/i.test(document.querySelector("#sampleTxt").textContent) && !/loading/.test(document.querySelector("#sampleTxt").textContent));
    const script = await page.textContent("#sampleTxt");
    check(/^-- Generated by ParamLens/.test(script) && /DECLARE @qplo/.test(script), `${label}: sample with DECLARE`);
    await page.click("#segSample button[data-v=statement]");
    check(/^exec sp_executesql N'SELECT count\(1\)/.test(await page.textContent("#sampleTxt")), `${label}: original statement`);
    await page.click("#segSample button[data-v=script]");
    await page.click("#btnCloseSample");
  } else {
    check((await page.$$("#tFamily [data-sample]")).length === 0, `${label}: no "sample" button in the report`);
  }
}

(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ acceptDownloads: true, viewport: { width: 1400, height: 900 } });
  const errors = [];
  ctx.on("page", p => p.on("pageerror", e => errors.push(e.message)));

  // ---------- 1) standalone HTML ----------
  const page = await ctx.newPage();
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("file://" + path.resolve(htmlPath));
  check(await page.isVisible("#vFile"), "html: file screen shows without a server");
  check(!(await page.isVisible("#vSetup")), "html: connection hidden");
  check((await page.getAttribute("html", "lang")) === "en" && /Drop the file here/.test(await page.textContent("#drop")), "html: English by default");
  const bcp = await page.textContent("#expBcp");
  check(/^bcp "SELECT x\.object_name,/.test(bcp) && /queryout "C:\\temp\\paramlens-events\.tsv" -S SERVER -d master -T -w$/.test(bcp), "html: bcp command for .xel");
  check(!/\n/.test(bcp), "html: bcp on a single line");
  await page.fill("#eServer", "SRV01\\INST");
  await page.click("#segExp button[data-v=table]");
  await page.fill("#eDb", "DBA");
  const bcp2 = await page.textContent("#expBcp");
  const sql2 = await page.textContent("#expSql");
  check(/FROM \[dbo\]\.\[__xe_event_file\] WHERE \[statement\] IS NOT NULL AND \[name\] = N'rpc_completed'/.test(bcp2) && /-S SRV01\\INST -d DBA -T -w$/.test(bcp2), "html: bcp for the table");
  check(sql2.includes("REPLACE(REPLACE(REPLACE(REPLACE(CAST([statement] AS nvarchar(max)), N'\\', N'\\\\'), NCHAR(13), N'\\r'), NCHAR(10), N'\\n'), NCHAR(9), N'\\t')"), "html: statement escaping in the query");
  await page.screenshot({ path: path.join(shots, "1-file.png"), fullPage: true });

  await analyzeFile(page, tsvPath);
  await checkResults(page, "html", { samples: true });
  await page.click("#mainTabs button[data-v=fails]");
  const fails = await page.textContent("#tFails");
  check(/Ignored: event sp_statement_completed\s*63/.test(fails), "html: ignored events counted");
  check(/UTF-16 LE/.test(fails) && /Header\s*yes/.test(fails), "html: encoding and header");
  check(/Period/.test(fails) && /not an EXEC call/.test(fails), "html: period and failure reasons");
  check(/Format\s*ParamLens TSV v1/.test(fails), "html: TSV format detected");

  // CSV with a header row (SELECT * saved by SSMS)
  const csvPath = path.join(path.dirname(tsvPath), "export.csv");
  if (fs.existsSync(csvPath)) {
    await page.click("#btnNew");
    await analyzeFile(page, csvPath);
    check((await page.$$("#famList .fam")).length === 16, "csv: 16 queries");
    await page.click("#mainTabs button[data-v=fails]");
    const fcsv = await page.textContent("#tFails");
    check(/Format\s*CSV · 14 columns/.test(fcsv) && /Ignored: event sp_statement_completed\s*63/.test(fcsv), "csv: format and ignored events");
    await page.click("#famList .fam");
    await page.click("#tFamily [data-sample]");
    await page.waitForFunction(() => /DECLARE/.test(document.querySelector("#sampleTxt").textContent));
    check(true, "csv: sample re-read from the file");
    await page.click("#btnCloseSample");
    await page.click("#mainTabs button[data-v=findings]");
    await page.click("#btnNew");
    await analyzeFile(page, tsvPath);
  }
  await page.click("#mainTabs button[data-v=findings]");
  await page.screenshot({ path: path.join(shots, "2-results-en.png") });

  // language switch keeps the analysis and translates engine text
  await page.selectOption("#langSel", "pt-BR");
  check((await page.getAttribute("html", "lang")) === "pt-BR" && /Todos os achados/.test(await page.textContent("#mainTabs")), "pt-BR: interface translated");
  const f0pt = await page.textContent("#tFindings .find .tt");
  check(/^Catch-all: @qploDropdownAssigneeId = 0 é verdadeiro em 90,\d% das execuções$/.test(f0pt), `pt-BR: finding translated with pt-BR numbers (${f0pt})`);
  check(/Execuções/.test(await page.textContent("#totKpis")), "pt-BR: KPIs");
  await page.click("#mainTabs button[data-v=fails]");
  check(/não é uma chamada EXEC/.test(await page.textContent("#tFails")) && /Ignoradas: evento sp_statement_completed/.test(await page.textContent("#tFails")), "pt-BR: failure reasons and file info");
  await page.click("#famList .fam");
  check(/Formatos de chamada/.test(await page.textContent("#tFamily")) && /filtra/.test(await page.textContent("#tFamily")), "pt-BR: query detail");
  await page.click("#tFamily [data-sample]");
  await page.waitForFunction(() => /DECLARE/.test(document.querySelector("#sampleTxt").textContent));
  check(/^-- Gerado pelo ParamLens/.test(await page.textContent("#sampleTxt")), "pt-BR: test script header");
  await page.click("#btnCloseSample");
  await page.click("#mainTabs button[data-v=findings]");
  await page.screenshot({ path: path.join(shots, "2-results-pt.png") });
  await page.reload();
  check((await page.getAttribute("html", "lang")) === "pt-BR" && /Arraste o arquivo aqui/.test(await page.textContent("#drop")), "pt-BR: choice remembered after reload");
  await page.selectOption("#langSel", "en");
  await analyzeFile(page, tsvPath);

  // ---------- 2) exported report ----------
  const [dl] = await Promise.all([page.waitForEvent("download"), page.click("#btnExport")]);
  const rep = path.join(shots, "report.html");
  await dl.saveAs(rep);
  check(/^paramlens-\d{8}-\d{4}\.html$/.test(dl.suggestedFilename()), `report: name ${dl.suggestedFilename()}`);
  const p2 = await ctx.newPage();
  await p2.goto("file://" + rep);
  await p2.waitForSelector("#vRes:not(.hidden)");
  await checkResults(p2, "report", { samples: false });
  check(!(await p2.isVisible("#btnExport")) && !(await p2.isVisible("#btnQuit")), "report: no export/quit");
  await p2.click("#mainTabs button[data-v=fails]");
  check(/Ignored: event sp_statement_completed/.test(await p2.textContent("#tFails")), "report: file info preserved");
  await p2.selectOption("#langSel", "pt-BR");
  check(/é verdadeiro em/.test(await p2.textContent("#tFindings")), "report: language switch works offline");
  await p2.selectOption("#langSel", "en");

  // file without rpc_completed
  await page.click("#btnNew");
  const only = path.join(shots, "only-others.tsv");
  fs.writeFileSync(only, "sp_statement_completed\t\t1\t1\t1\t0\t0\t0\tSELECT 1\nsql_statement_completed\t\t1\t1\t1\t0\t0\t0\tSELECT 2\n");
  await page.setInputFiles("#fFile", only);
  await page.click("#btnFileAnalyze");
  await page.waitForFunction(() => /no "rpc_completed" event/.test(document.querySelector("#fMsg").textContent));
  check(/ignored: 1 of sp_statement_completed, 1 of sql_statement_completed/.test(await page.textContent("#fMsg")), "html: message when there is no rpc_completed");

  // ---------- 3) server (.exe) ----------
  if (binPath) {
    const srv = spawn(binPath, ["-port", "8799", "-no-browser"], { stdio: ["ignore", "pipe", "inherit"] });
    let out = "";
    srv.stdout.on("data", d => { out += d; });
    for (let i = 0; i < 50 && !/t=[0-9a-f]+/.test(out); i++) await new Promise(r => setTimeout(r, 100));
    check(/parameter profiling for rpc_completed/.test(out) && /Only accepts connections from this machine/.test(out), "exe: console in English");
    const url = out.match(/http:\/\/127\.0\.0\.1:\d+\/\?t=[0-9a-f]+/)[0];
    const p3 = await ctx.newPage();
    await p3.goto(url);
    check(await p3.isVisible("#vSetup") && !(await p3.isVisible("#vFile")), "exe: connection screen");
    await p3.click("#btnDemo");
    await p3.waitForSelector("#vRes:not(.hidden)", { timeout: 60000 });
    check((await p3.$$("#famList .fam")).length === 3, "exe: demo analyzed on the server");
    check(/sample data/.test(await p3.textContent("#hdrSub")), "exe: header label");
    await p3.click("#famList .fam");
    await p3.click("#tFamily [data-sample]");
    await p3.waitForFunction(() => /DECLARE/.test(document.querySelector("#sampleTxt").textContent));
    check(true, "exe: sample through the API");
    await p3.click("#btnCloseSample");
    await p3.selectOption("#langSel", "pt-BR");
    check(/dados de exemplo/.test(await p3.textContent("#hdrSub")) && /verdadeiro em/.test(await p3.textContent("#tFamily")), "exe: pt-BR on server data");
    await p3.selectOption("#langSel", "en");
    await p3.click("#btnNew");
    await p3.click("#btnToFile");
    check(await p3.isVisible("#vFile") && await p3.isVisible("#fBackSrv"), "exe: switch to file mode");
    await analyzeFile(p3, tsvPath);
    check((await p3.$$("#famList .fam")).length === 16, "exe: file analyzed in the browser");
    const [dl3] = await Promise.all([p3.waitForEvent("download"), p3.click("#btnExport")]);
    check(/^paramlens-/.test(dl3.suggestedFilename()), "exe: local export in file mode");
    await p3.click("#btnNew");
    await p3.click("#btnToSrv");
    check(await p3.isVisible("#vSetup"), "exe: back to the connection");
    await p3.screenshot({ path: path.join(shots, "3-exe.png") });
    srv.kill();
  }

  check(errors.length === 0, "no JavaScript errors" + (errors.length ? ": " + errors.join(" | ") : ""));
  await browser.close();
  if (failures) { console.log(`\n${failures} check(s) failed`); process.exit(1); }
  console.log("\nUI: OK");
})().catch(e => { console.error(e); process.exit(2); });
