#!/usr/bin/env node
// UI smoke test in a real Chromium (Playwright).
//   node scripts/ui-smoke.js dist/ParamLens.html dist/parity/export.tsv [linux-binary]
// 1) ParamLens.html over file:// (file mode), language switch, 2) exported report,
// 3) the server (.exe) with demo data and the switch to file mode. Screenshots in dist/shots/.
"use strict";
const path = require("path");
const fs = require("fs");
const { spawn } = require("child_process");
const { chromium } = require("playwright");

const [htmlPath, tsvPath, binPath] = process.argv.slice(2);
const shots = path.resolve("dist/shots");
fs.mkdirSync(shots, { recursive: true });
let failures = 0;
const check = (cond, msg) => { console.log((cond ? "ok     " : "FAILED ") + msg); if (!cond) failures++; };

async function analyzeFile(page, tsv) {
  await page.setInputFiles("#fFile", tsv);
  await page.click("#btnFileAnalyze");
  await page.waitForSelector("#vRes:not(.hidden)", { timeout: 60000 });
}

async function checkResults(page, label, { samples }) {
  const fams = await page.$$eval("#famList .fam", els => els.length);
  check(fams === 18, `${label}: 18 queries in the list (${fams})`);
  const sorts = await page.$$eval("#famSort option", os => os.map(o => o.value));
  check(sorts[0] === "sum:2" && sorts.includes("avg:1") && sorts.includes("avg:0") && sorts.includes("sev"), `${label}: sort options per metric (${sorts.join(" ")})`);
  await page.selectOption("#famSort", "avg:2");
  const byAvg = await page.evaluate(() => {
    const ids = [...document.querySelectorAll("#famList .fam")].map(e => +e.dataset.id);
    const a = id => { const f = ov.families.find(x => x.id === id); return f.agg.sum[2] / f.agg.count };
    return ids.every((id, i) => i === 0 || a(ids[i - 1]) >= a(id)) && /avg logical reads/.test(document.querySelector("#famList .fam .m").textContent);
  });
  check(byAvg, `${label}: sorted by average logical reads`);
  await page.selectOption("#famSort", "sum:2");
  const kpi = await page.textContent("#totKpis");
  check(/Executions/.test(kpi) && /Findings/.test(kpi), `${label}: KPIs in English`);
  const nFind = await page.$$eval("#tFindings .find", els => els.length);
  check(nFind >= 30, `${label}: findings listed (${nFind})`);
  const f0 = await page.textContent("#tFindings .find .tt");
  check(/^Catch-all: @qploDropdownCarrierId = 0 is true in 90\.\d% of executions$/.test(f0), `${label}: finding text built by the UI (${f0})`);
  await page.click("#famList .fam");
  await page.waitForSelector("#tFamily:not(.hidden) #ptab");
  const params = await page.$$eval("#ptab tr.click", els => els.length);
  check(params > 5, `${label}: parameter table (${params})`);
  await page.click("#ptab tr.click");
  check(await page.isVisible("#pd0:not(.hidden) table"), `${label}: value distribution opens`);
  const fam = await page.textContent("#tFamily");
  check(/Call shapes/.test(fam) && /pass-through/.test(fam) && /filter/.test(fam), `${label}: call shapes`);
  if (samples) {
    const before = await page.textContent("#comboTab");
    await page.click("#chips .chip:not(.on)");
    await page.waitForFunction(b => document.querySelector("#comboTab").textContent !== b && !/computing/.test(document.querySelector("#comboTab").textContent), before);
    check(/combination/.test(await page.textContent("#comboTab")), `${label}: combination recomputed`);
    await page.click("#tFamily [data-sample]");
    await page.waitForFunction(() => /DECLARE|exec/i.test(document.querySelector("#sampleTxt").textContent) && !/loading/.test(document.querySelector("#sampleTxt").textContent));
    const script = await page.textContent("#sampleTxt");
    check(/^-- Generated by ParamLens/.test(script) && /DECLARE @qplo/.test(script), `${label}: sample with DECLARE`);
    await page.click("#segSample button[data-v=statement]");
    check(/^exec sp_executesql N'SELECT count\(1\)/.test(await page.textContent("#sampleTxt")), `${label}: original statement`);
    await page.click("#segSample button[data-v=script]");
    await page.click("#btnCloseSample");
  } else {
    check((await page.$$("#tFamily [data-sample]")).length === 0, `${label}: no "sample" button in the report`);
  }
}

async function download(page, sel) {
  const [d] = await Promise.all([page.waitForEvent("download"), page.click(sel)]);
  return { name: d.suggestedFilename(), text: fs.readFileSync(await d.path(), "utf8").replace(/^﻿/, "") };
}

// parameter export (script / CSV, per execution and per combination) of the query on screen
async function checkParamExport(page, label, { db }) {
  await page.click("#btnPx");
  check(await page.isVisible("#pxOv"), `${label}: export dialog opens`);
  check((await page.isVisible("#pxDbTab")) === db, `${label}: "insert into a database" ${db ? "offered" : "hidden without the .exe"}`);
  const execs = +(await page.textContent("#pxInfo")).match(/^([\d,]+) executions/)[1].replace(/,/g, "");
  const s = await download(page, "#btnPxGo");
  const tuples = s.text.split("\n").filter(l => /^\(\d+, /.test(l)).length;
  check(/^paramlens-params-\d+-execs\.sql$/.test(s.name) && /CREATE TABLE \[dbo\]\.\[paramlens_params\] \(\n  \[exec_no\] int NOT NULL,/.test(s.text)
    && /SET DATEFORMAT ymd;/.test(s.text) && tuples === execs, `${label}: script with one row per execution (${tuples}/${execs})`);
  check(/DECLARE @run bit = 0;/.test(s.text) && /EXEC sp_executesql @stmt, @params, @\w+ = @v1/.test(s.text), `${label}: replay loop`);
  check(/^-- ParamLens: parameters/.test(await page.textContent("#pxMsg")) === false && /rows exported/.test(await page.textContent("#pxMsg")), `${label}: export message`);
  await page.click("#segPx button[data-v=csv]");
  const c = await download(page, "#btnPxGo");
  const lines = c.text.trim().split("\r\n");
  check(/^exec_no;/.test(lines[0]) && lines.length === execs + 1, `${label}: CSV with a header and one line per execution`);
  await page.selectOption("#pxMode", "combos");
  await page.click("#segPx button[data-v=script]");
  const k = await download(page, "#btnPxGo");
  check(/\[combo_no\] int NOT NULL,\n  \[executions\] int NULL,/.test(k.text) && /avg_/.test(k.text), `${label}: script per combination`);
  await page.selectOption("#pxMode", "execs");
  await page.click("#btnClosePx");
}

// hard-coded values of the selected query (the sample order query has two IN lists)
async function checkHardCoded(page, label) {
  await page.click("#famList .fam");
  await page.waitForSelector("#tFamily:not(.hidden) #btnPx");
  await page.click("#btnPx");
  await page.waitForSelector("#pxCols input[data-px]");
  const lits = await page.$$eval('#pxCols input[data-px^="l:"]', es => es.map(e => ({ on: e.checked, text: e.closest("label").textContent })));
  const list = lits.find(l => /IN list/.test(l.text));
  check(!!list && list.on && /nvarchar\(max\)/.test(list.text), `${label}: IN list offered as nvarchar(max) and suggested (${lits.length} hard-coded value(s))`);
  await page.click("#segPx button[data-v=script]");
  const s = await download(page, "#btnPxGo");
  check(/\[\w+_list\] nvarchar\(max\) NULL/.test(s.text) && /N'\d+(,\d+)+'/.test(s.text), `${label}: list values exported separated by commas`);
  check(/IN \(SELECT value FROM STRING_SPLIT\(@\w+_list, N'',''\)\)/.test(s.text) && /@\w+_list nvarchar\(max\)/.test(s.text), `${label}: replay passes the list through STRING_SPLIT`);
  await page.click('#pxCols input[data-px="p:0"]');
  check(await page.isDisabled("#pxReplay") && await page.isVisible("#pxReplayNote"), `${label}: the replay needs every parameter`);
  await page.click('#pxCols input[data-px="p:0"]');
  check(!(await page.isDisabled("#pxReplay")), `${label}: replay enabled again`);
  await page.click("#btnClosePx");
}

// executions of the selected query over time: one row each, grouped per hour / hour of the day, CSV
async function checkTimeline(page, label) {
  await page.click("#famList .fam");
  await page.waitForSelector("#tFamily:not(.hidden) #btnTl");
  const execs = await page.evaluate(() => curDetail.summary.agg.count);
  await page.click("#btnTl");
  await page.waitForSelector("#tlTab table");
  const num = s => +s.replace(/[^\d]/g, "");
  const n = await page.$$eval("#tlTab tr", trs => trs.length - 1);
  check(n === Math.min(execs, 2000) && /executions from \d{4}-\d\d-\d\d/.test(await page.textContent("#tlInfo")), `${label}: executions listed one per row (${n} of ${execs})`);
  const ts = await page.$$eval("#tlTab tr td:nth-child(2)", tds => tds.map(td => td.textContent));
  check(ts.every((x, i) => i === 0 || ts[i - 1] <= x) && /^\d{4}-\d\d-\d\d \d\d:\d\d:\d\d\.\d{3}$/.test(ts[0]), `${label}: in time order (${ts[0]})`);
  for (const [g, max] of [["h", Infinity], ["hod", 24], ["dow", 7]]) {
    await page.selectOption("#tlGroup", g);
    const cnt = await page.$$eval("#tlTab tr td:nth-child(2)", tds => tds.map(td => td.textContent));
    const sum = cnt.reduce((a, x) => a + num(x), 0);
    check(sum === execs && cnt.length >= 1 && cnt.length <= max, `${label}: grouped by ${g}, ${cnt.length} period(s), ${sum} executions`);
  }
  await page.click("#tlTab th[data-c='1']"); // executions, highest first
  const desc = (await page.$$eval("#tlTab tr td:nth-child(2)", tds => tds.map(td => td.textContent))).map(num);
  check(desc.every((x, i) => i === 0 || desc[i - 1] >= x), `${label}: sorted by a column`);
  const csv = await download(page, "#btnTlCsv");
  check(/^"period";"executions";"avg_duration_us"/.test(csv.text), `${label}: CSV of the groups (${csv.name})`);
  await page.selectOption("#tlGroup", "exec");
  await page.click("#tlTab [data-sample]");
  await page.waitForFunction(() => /exec/i.test(document.querySelector("#sampleTxt").textContent) && !/loading/.test(document.querySelector("#sampleTxt").textContent));
  await page.keyboard.press("Escape");
  check(await page.isHidden("#sampleOv") && await page.isVisible("#tlOv"), `${label}: the sample of one execution opens over the list`);
  await page.keyboard.press("Escape");
  check(await page.isHidden("#tlOv"), `${label}: Escape closes the list`);
}

// baseline × current analysis, saved and loaded back
async function checkCompare(page, label) {
  await page.click("#mainTabs button[data-v=compare]");
  await page.waitForSelector("#tCompare [data-cmp=same]");
  await page.click("#tCompare [data-cmp=same]");
  await page.waitForSelector("#tCompare select[data-side=cur]");
  check(/same/.test(await page.textContent("#cmpOut")), `${label}: a query compared with itself is "same"`);
  const opts = await page.$$eval("select[data-side=cur] option", os => os.map(o => o.value));
  await page.selectOption("select[data-side=cur]", opts[opts.length - 1]);
  await page.waitForFunction(() => /[−+]\d/.test(document.querySelector("#cmpOut").textContent));
  const out = await page.textContent("#cmpOut");
  check(/p95/.test(out) && /Average/.test(out) && /Executions/.test(out), `${label}: comparison of two queries of the same capture`);
  const before = await page.textContent("#cmpOut .kpis");
  await page.click("#tCompare [data-cmp=swap]");
  await page.waitForFunction(b => document.querySelector("#cmpOut .kpis").textContent !== b, before);
  check(/A \(original\)/.test(await page.textContent("#tCompare")), `${label}: A and B swapped`);
  await page.click("#tCompare [data-cmp=swap]");
  const b = await download(page, "#tCompare [data-cmp=save]");
  const j = JSON.parse(b.text);
  check(j.paramlens === "baseline" && j.fams.length === opts.length && j.fams[0].d.some(Boolean), `${label}: kept capture saved (${j.fams.length} queries)`);
  await page.click("#tCompare [data-cmp=clear]");
  const f = path.join(shots, "baseline.json");
  fs.writeFileSync(f, b.text);
  await page.setInputFiles("#cmpFile", f);
  await page.waitForSelector("#tCompare select[data-side=base]");
  check(true, `${label}: saved capture loaded from the file`);
  await page.selectOption("#langSel", "pt-BR");
  check(/Comparar desempenho/.test(await page.textContent("#tCompare")) && /Média/.test(await page.textContent("#cmpOut")), `${label}: comparison in pt-BR`);
  await page.selectOption("#langSel", "en");
  await page.click("#mainTabs button[data-v=findings]");
}

// "compare with another capture": the analysis on screen is kept as A, B comes from the source screen
async function checkCompareOther(page, label, analyze) {
  await page.click("#mainTabs button[data-v=compare]");
  await page.waitForSelector("#tCompare [data-cmp=other]");
  await page.click("#tCompare [data-cmp=other]");
  await page.waitForSelector("#vRes.hidden", { state: "attached" });
  check(await page.isVisible("#cmpBanner") && /is kept as A/.test(await page.textContent("#cmpBanner")), `${label}: source screen with the comparison banner`);
  await page.click("#btnCmpCancel");
  await page.waitForSelector("#vRes:not(.hidden)");
  check(!(await page.isVisible("#cmpBanner")), `${label}: cancel goes back to the results`);
  await page.click("#mainTabs button[data-v=compare]");
  await page.click("#tCompare [data-cmp=other]");
  await analyze();
  await page.waitForSelector("#tCompare:not(.hidden) select[data-side=cur]", { timeout: 60000 });
  check(/Kept capture/.test(await page.textContent("#tCompare")) && /[−+]\d|same/.test(await page.textContent("#cmpOut")), `${label}: comparison opens after analyzing the other capture`);
  await page.click("#mainTabs button[data-v=findings]");
}

async function noHorizontalScroll(page, label) {
  for (let i = 0; i < 3; i++) {
    await (await page.$$("#famList .fam"))[i].click();
    await page.waitForSelector("#tFamily:not(.hidden) #ptab");
    const w = await page.evaluate(() => [document.documentElement.scrollWidth, document.documentElement.clientWidth]);
    if (w[0] > w[1]) { check(false, `${label}: page wider than the window (${w[0]} > ${w[1]})`); return; }
  }
  check(true, `${label}: no horizontal page scroll`);
}

